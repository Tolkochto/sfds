"""
Утилиты для аффинных преобразований координат.
Используются для масштабирования и переноса скелета пользователя
под пропорции эталонного скелета (Прокрустов анализ).
"""

import numpy as np

def pad(x):
    """
    Добавляет столбец единиц к матрице координат для выполнения
    матричного умножения при аффинных преобразованиях.

    Args:
        x (np.ndarray): Матрица координат формы (N, 2).

    Returns:
        np.ndarray: Матрица формы (N, 3).
    """
    return np.hstack([x, np.ones((x.shape[0], 1))])

def unpad(x):
    """
    Удаляет вспомогательный столбец после завершения аффинного преобразования.

    Args:
        x (np.ndarray): Матрица формы (N, 3).

    Returns:
        np.ndarray: Восстановленная матрица координат формы (N, 2).
    """
    return x[:, :-1]

def get_affine_transform(pts1, pts2):
    """
    Вычисляет матрицу аффинного преобразования методом наименьших квадратов (МНК).
    Находит такую матрицу A, при которой pts1 * A максимально приближается к pts2.

    Args:
        pts1 (np.ndarray): Исходные координаты (скелет пользователя), форма (17, 2).
        pts2 (np.ndarray): Целевые координаты (скелет коуча), форма (17, 2).

    Returns:
        np.ndarray: Матрица преобразования A.
    """
    # Подготавливаем матрицу, добавляя столбец единиц
    pts1_padded = pad(pts1)

    # Решаем систему линейных уравнений методом наименьших квадратов
    A, residuals, rank, s = np.linalg.lstsq(pts1_padded, pts2, rcond=None)

    return A