"""
Метрики для оценки схожести поз (скелетов).
Содержит функции для расчета косинусного сходства (геометрия позы)
и взвешенного евклидова расстояния (ошибки в пикселях).
"""

import numpy as np

def cosine_distance(pose1, pose2):
    """
    Вычисляет центрированное косинусное сходство между двумя позами.
    Оценивает схожесть формы (углов сгибания суставов), игнорируя
    положение скелета в пространстве.

    Args:
        pose1 (np.ndarray): Координаты первого скелета, форма (17, 2).
        pose2 (np.ndarray): Координаты второго скелета (эталона), форма (17, 2).

    Returns:
        float: Значение от -1.0 до 1.0 (где 1.0 — абсолютное совпадение форм).
    """
    # Находим центры масс для каждого скелета (среднее по x и y)
    center1 = np.mean(pose1, axis=0)
    center2 = np.mean(pose2, axis=0)

    # Центрируем позы (вычитаем центр масс)
    p1_centered = pose1 - center1
    p2_centered = pose2 - center2

    # Вытягиваем в одномерные векторы (размерность 34)
    v1 = p1_centered.flatten()
    v2 = p2_centered.flatten()

    # Считаем длину (норму) векторов
    norm1 = np.linalg.norm(v1)
    norm2 = np.linalg.norm(v2)

    # Защита от деления на ноль
    if norm1 == 0 or norm2 == 0:
        return 0.0

    # Формула косинусного сходства (скалярное произведение деленное на произведение норм)
    return np.dot(v1, v2) / (norm1 * norm2)


def weight_distance(pose1, pose2, conf1):
    """
    Вычисляет среднее взвешенное расстояние (ошибку) между суставами в пикселях.
    Чем больше уверенность нейросети (conf) в конкретной точке,
    тем сильнее её отклонение влияет на итоговую ошибку.

    Args:
        pose1 (np.ndarray): Координаты трансформированного скелета пользователя (17, 2).
        pose2 (np.ndarray): Координаты эталонного скелета (17, 2).
        conf1 (np.ndarray): Массив уверенности модели для точек пользователя (17,).

    Returns:
        float: Средневзвешенная дистанция ошибки в пикселях.
    """
    # Считаем разницу координат по x и y для каждой из 17 точек
    diff = pose1 - pose2

    # Вычисляем евклидово расстояние (гипотенузу) для каждой точки
    distances = np.linalg.norm(diff, axis=1)

    # Взвешиваем расстояния на уверенность нейросети
    weighted_distances = distances * conf1

    # Сумма всех весов
    sum_conf = np.sum(conf1)

    # Защита от деления на ноль
    if sum_conf == 0:
        return 0.0

    # Итоговое средневзвешенное отклонение
    return np.sum(weighted_distances) / sum_conf